"""Exercise the checked-in fixture publications through the production parsers."""
import gzip
import json
from pathlib import Path
import sys
import tempfile
import unittest

if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from api.fixtures import FixtureFleet
from collector.inventory import CapacityThresholds
from collector.view import server_bytes
from tools.gen_sample import SNAPSHOTS, write_server

DATA_DIR = Path(__file__).parent / "fixtures/fleet"


class FixtureTest(unittest.TestCase):
    def test_reproducible(self):
        """Regenerated fixtures carry the checked-in content.

        Gzip bytes, and so capture names and sizes, depend on the zlib build
        (CI's Python 3.12 and a host's Python 3.10 differ), so captures are
        compared by their decompressed JSON and manifests after mapping each
        regenerated capture name to the checked-in one with the same content.
        """
        def payloads(directory):
            return {gzip.decompress(p.read_bytes()): p for p in directory.glob("*.json.gz")}

        with tempfile.TemporaryDirectory() as tmp:
            directory = Path(tmp)
            for _, factory in SNAPSHOTS:
                write_server(directory, factory())
            fresh, kept = payloads(directory), payloads(DATA_DIR)
            self.assertEqual(set(fresh), set(kept))
            rename = {}
            for content, path in fresh.items():
                old = kept[content]
                rename[path.name.split(".")[0]] = (old.name.split(".")[0], old.stat().st_size, path.stat().st_size)
            for path in sorted(directory.glob("*.json")):
                text = path.read_text()
                for new_sha, (old_sha, old_size, new_size) in rename.items():
                    text = text.replace(new_sha, old_sha)
                    text = text.replace(f'"bytes": {new_size},', f'"bytes": {old_size},')
                self.assertEqual(json.loads(text), json.loads((DATA_DIR / path.name).read_text()), path.name)
            # hosts.json is the hand-written inventory, not generated by write_server.
            self.assertEqual({p.name for p in directory.glob("*.json")} | {"hosts.json"},
                             {p.name for p in DATA_DIR.glob("*.json")})

    def test_volumes_list_home_first_then_root_then_alphabetical(self):
        fleet = FixtureFleet(DATA_DIR)
        orders = {}
        for sid in ("hinton", "orion", "zeus"):
            detail = json.loads(server_bytes(fleet.view(sid), fleet.clock.monotonic(), CapacityThresholds(), detail=True))
            orders[sid] = [(v["mountpoint"], [r["scan_root"] for r in v["roots"]]) for v in detail["volumes"]]
            row = json.loads(server_bytes(fleet.view(sid), fleet.clock.monotonic(), CapacityThresholds()))
            self.assertEqual([v["mountpoint"] for v in row["volumes"]], [m for m, _ in orders[sid]])
        self.assertEqual(orders["hinton"], [("/home", ["/home"]), ("/", ["/data", "/data1"]), ("/data3", ["/data3"])])
        self.assertEqual([m for m, _ in orders["orion"]], ["/srv/orion/vol1", "/srv/orion/vol2"])

    def test_hinton_unreadable_directories(self):
        fleet = FixtureFleet(DATA_DIR)
        view = fleet.view("hinton")
        detail = json.loads(server_bytes(view, fleet.clock.monotonic(), CapacityThresholds(), detail=True))
        expected = {"/home": "/home/jusung", "/data": "/data/private_collab"}
        reported = []
        for volume in detail["volumes"]:
            vid = volume["volume_id"]
            raw = fleet.read_capture("hinton", vid, volume["capture"]["sha256"])
            capture = json.loads(gzip.decompress(raw))
            for root in capture["roots"]:
                path = expected.get(root["scan_root"])
                self.assertEqual(root["counts"]["errors"], int(path is not None))
                if path:
                    self.assertEqual(root["outcome"], "partial")
                    self.assertEqual(volume["capture"]["outcome"], "partial")
                    self.assertEqual(root["errors"], [{"path": path, "reason": "EACCES"}])
                    reported.append({**root["errors"][0], "volume_id": vid, "binding": root["binding"]})
        self.assertEqual(len(reported), 2)
        self.assertCountEqual(detail["errors"], reported)

    def test_manifest_cases(self):
        fleet = FixtureFleet(DATA_DIR)
        self.assertEqual(fleet.view("orion").transport, "legacy")
        self.assertEqual(fleet.view("hinton").transport, "gate")
        volumes = [v for view in fleet.views() for v in view.publication.manifest.volumes]
        self.assertTrue(any(len(v.roots) > 1 for v in volumes))
        self.assertTrue(any(v.identity == "ambiguous" for v in volumes))
        self.assertTrue(any(v.last_attempt and v.last_attempt.outcome == "failed" and v.capture for v in volumes))
        self.assertTrue(any(v.capacity.status == "failed" for v in volumes))


if __name__ == "__main__":
    unittest.main()
